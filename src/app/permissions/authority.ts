/**
 * `authorities` is optional in the API contract, so an absent list fails closed:
 * a member without a returned authority list is granted nothing.
 */
export function hasAuthority(
  authorization: Pick<MemberAuthorization, "authorities"> | null | undefined,
  requiredAuthority?: string | null,
): boolean {
  return !requiredAuthority || authorization?.authorities?.includes(requiredAuthority) === true;
}
